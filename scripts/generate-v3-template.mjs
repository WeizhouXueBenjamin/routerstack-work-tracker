import {readFileSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const JSZip=require(resolve(root,'vendor/jszip.min.js'));
const Core=require(resolve(root,'src/core.js'));
const escape=value=>String(value).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
const zip=await JSZip.loadAsync(readFileSync(resolve(root,'templates/RouterStack_Tracker_V2_Blank.xlsx')));
function replaceCell(xml,ref,content,type='str') {
  const pattern=new RegExp('<x:c r="'+ref+'"[^>]*?(?:/>|>[\\s\\S]*?</x:c>)');
  const current=xml.match(pattern)?.[0];
  if(!current)throw Error('Missing template cell '+ref);
  const style=current.match(/\bs="([^"]+)"/)?.[1];
  return xml.replace(pattern,()=>`<x:c r="${ref}"${style?` s="${style}"`:''} t="${type}">${content}</x:c>`);
}
let log=await zip.file('xl/worksheets/sheet2.xml').async('string');
for(let row=6;row<=305;row++)for(const [col,formula] of Object.entries(Core.formulas(row)))log=replaceCell(log,col+row,'<x:f>'+escape(formula)+'</x:f>');
