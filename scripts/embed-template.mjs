import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
for(const [version,name,identifier]of [['5','template-data.js','TEMPLATE_BASE64']]) {
  const workbook=readFileSync(resolve(root,`templates/RouterStack_Tracker_V${version}_Blank.xlsx`));
  const output=resolve(root,'src',name);
  const content=`// Generated by npm run template:sync. Do not edit manually.\nconst ${identifier}='${workbook.toString('base64')}';\n`;
  if(process.argv.includes('--check')) {
    if(readFileSync(output,'utf8')!==content){console.error(name+' is out of sync. Run: npm run template:sync');process.exitCode=1}
    else console.log('Workbook/'+name+' match.');
  } else {writeFileSync(output,content);console.log('Updated '+name)}
}
