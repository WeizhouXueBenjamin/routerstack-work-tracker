import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const workbook = readFileSync(resolve(root, 'templates/RouterStack_Tracker_V3_Blank.xlsx'));
const output = resolve(root, 'src/template-data.js');
const content = `// Generated by npm run template:sync. Do not edit manually.\nconst TEMPLATE_BASE64='${workbook.toString('base64')}';\n`;
if (process.argv.includes('--check')) {
  const current = readFileSync(output, 'utf8');
  if (current !== content) {
    console.error('Embedded template is out of sync. Run: npm run template:sync');
    process.exitCode = 1;
  } else console.log('Workbook/template-data.js match.');
} else {
  writeFileSync(output, content);
  console.log('Updated embedded workbook template.');
}
